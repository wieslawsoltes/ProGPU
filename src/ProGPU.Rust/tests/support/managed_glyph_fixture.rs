use progpu::text::ManagedShapingGlyph;
pub fn words(g: ManagedShapingGlyph) -> [u32; 31] {
    [
        g.glyph_index as u32,
        g.cluster as u32,
        g.grapheme_cluster as u32,
        g.character_cluster as u32,
        g.code_point,
        g.flags,
        g.advance_x as u32,
        g.advance_y as u32,
        g.offset_x as u32,
        g.offset_y as u32,
        g.arabic_action as u32,
        g.space_fallback as u32,
        g.fraction_action as u32,
        g.script_feature_mask as u32,
        g.script_shaper as u32,
        g.use_category as u32,
        g.use_syllable as u32,
        g.indic_category as u32,
        g.indic_position as u32,
        g.indic_original_order as u32,
        g.use_rphf_eligible as u32,
        g.substituted as u32,
        g.ligated as u32,
        g.multiple_substitution_component as u32,
        g.multiplied as u32,
        g.ligature_component_count as u32,
        g.ligature_component as u32,
        g.has_character_cluster as u32,
        g.positioned as u32,
        g.attachment_kind as u32,
        g.attachment_target as u32,
    ]
}

pub fn from_words(w: &[u32]) -> ManagedShapingGlyph {
    assert_eq!(w.len(), 31);
    ManagedShapingGlyph {
        glyph_index: w[0] as u16,
        cluster: w[1] as i32,
        grapheme_cluster: w[2] as i32,
        character_cluster: w[3] as i32,
        code_point: w[4],
        flags: w[5],
        advance_x: w[6] as i16,
        advance_y: w[7] as i16,
        offset_x: w[8] as i16,
        offset_y: w[9] as i16,
        arabic_action: w[10] as u8,
        space_fallback: w[11] as u8,
        fraction_action: w[12] as u8,
        script_feature_mask: w[13] as u8,
        script_shaper: w[14] as u8,
        use_category: w[15] as u8,
        use_syllable: w[16] as u8,
        indic_category: w[17] as u8,
        indic_position: w[18] as u8,
        indic_original_order: w[19] as u8,
        use_rphf_eligible: w[20] as u8,
        substituted: w[21] as u8,
        ligated: w[22] as u8,
        multiple_substitution_component: w[23] as u8,
        multiplied: w[24] as u8,
        ligature_component_count: w[25] as u8,
        ligature_component: w[26] as u8,
        has_character_cluster: w[27] as u8,
        positioned: w[28] as u8,
        attachment_kind: w[29] as u8,
        attachment_target: w[30] as i32,
    }
}
